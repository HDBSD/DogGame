"""Regenerate embedded Vulkan shaders; normal builds need no shader compiler.

Usage: python scripts/compile_vulkan_shaders.py --compiler path/to/glslang.exe
The HLSL is shared with the retained D3D11 implementation. Only Vulkan's Y
convention changes; binding shifts keep constants, images and samplers distinct.
"""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--compiler", required=True)
args = parser.parse_args()
backend = root / "runtime_overrides/src/kernel"
source = (backend / "nv2a_gpu.cpp").read_text(encoding="utf-8")
shader = source.split('static const char shader[]=R"(', 1)[1].split(')";', 1)[0]
shader = shader.replace("(1-v.p.y*2/viewport.y)*w", "(v.p.y*2/viewport.y-1)*w")
digest = hashlib.sha256(shader.encode()).hexdigest()
output = ["/* Generated by scripts/compile_vulkan_shaders.py. Do not edit.\n",
          f" * Vulkan-adjusted HLSL SHA256: {digest}\n */\n"]
with tempfile.TemporaryDirectory() as directory:
    path = Path(directory)
    hlsl = path / "nv2a.hlsl"
    # Specialize simple modes at pipeline creation to remove the general
    # combiner interpreter, matching the retained D3D11 shader optimization.
    specialized = '[[vk::constant_id(0)]] const uint drawMode = 0;\n' + shader.replace("flags.x", "drawMode")
    hlsl.write_text(specialized)
    for stage, entry in [("vert", "vertex"), ("frag", "pixel")]:
        binary = path / f"{stage}.spv"
        subprocess.run([args.compiler, "-D", "-V", "--target-env", "vulkan1.0",
                        "--hlsl-iomap", "--auto-map-locations", "--auto-map-bindings",
                        "--shift-texture-binding", "1", "--shift-sampler-binding", "5",
                        "-S", stage, "-e", entry, "-o", str(binary), str(hlsl)], check=True)
        data = binary.read_bytes()
        words = struct.unpack(f"<{len(data) // 4}I", data)
        output.append(f"static const uint32_t nv_vk_{stage}_spirv[] = {{\n")
        for index in range(0, len(words), 8):
            output.append("    " + ", ".join(f"0x{word:08x}u" for word in words[index:index+8]) + ",\n")
        output.append("};\n")
(backend / "nv2a_vulkan_shaders.h").write_text("".join(output))
